import UIKit

public extension UIColor {
    static var appBlack: UIColor {
        return .appBlack
    }
    
    static var appBlack90: UIColor {
        return .appBlack90
    }
    
    static var appWhite: UIColor {
        return .appWhite
    }
    
    static var appPurple: UIColor {
        return .appPurple
    }
    
    static var appLightPurple: UIColor {
        return .appLightPurple
    }
    
    static var limeGreen: UIColor {
        return .limeGreen
    }
}
