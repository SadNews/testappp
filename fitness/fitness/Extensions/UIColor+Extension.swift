        return FitnessAsset.appPurple.color
    }
    
    static var appLightPurple: UIColor {
        return FitnessAsset.appLightPurple.color
    }
    
    static var limeGreen: UIColor {
        return FitnessAsset.limeGreen.color
    }
}
